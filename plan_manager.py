"""
plan_manager.py — Manages Implementation Plans, brainstorming documents,
and completed task Walkthrough artifacts for remote mobile workflows.
Organizes historical snapshots into an archive/ subfolder.
"""

import json
import logging
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional

logger = logging.getLogger(__name__)


class PlanManager:
    """Manages implementation plans and completed task walkthrough artifacts."""

    def __init__(self, project_dir: str):
        self.project_dir = project_dir

    @property
    def plans_dir(self) -> Path:
        p = Path(self.project_dir) / ".agent" / "plans"
        p.mkdir(parents=True, exist_ok=True)
        return p

    @property
    def archive_dir(self) -> Path:
        p = self.plans_dir / "archive"
        p.mkdir(parents=True, exist_ok=True)
        return p

    @property
    def active_plan_file(self) -> Path:
        return self.plans_dir / "implementation_plan.md"

    @property
    def active_walkthrough_file(self) -> Path:
        return self.plans_dir / "walkthrough.md"

    def save_plan(self, title: str, content: str) -> Path:
        """Save active implementation plan and tuck timestamped copy in archive/."""
        now = datetime.now(timezone.utc)
        timestamp = now.strftime("%Y%m%d_%H%M%S")

        header = (
            f"# 📋 Implementation Plan: {title}\n"
            f"*Created: {now.strftime('%Y-%m-%d %H:%M:%S UTC')}*\n"
            f"*Status: Draft / Brainstorming*\n\n---\n\n"
        )
        full_content = header + content.strip() + "\n"

        # 1. Save top-level active plan
        self.active_plan_file.write_text(full_content, encoding="utf-8")

        # 2. Save historical copy in archive/ subfolder
        history_file = self.archive_dir / f"plan_{timestamp}.md"
        history_file.write_text(full_content, encoding="utf-8")

        logger.info("Saved active plan to %s (archived to %s)", self.active_plan_file, history_file)
        return self.active_plan_file

    def get_active_plan(self) -> Optional[str]:
        """Read current active implementation plan if it exists."""
        if self.active_plan_file.exists():
            try:
                return self.active_plan_file.read_text(encoding="utf-8")
            except Exception as e:
                logger.error("Error reading active plan: %s", e)
        return None

    def save_walkthrough(
        self,
        title: str,
        execution_response: str,
        files_modified: Optional[List[str]] = None,
    ) -> Path:
        """
        Record a completed task walkthrough documenting:
        - Completed milestones & tasks
        - Files modified/created
        - Verification results
        Archives previous runs into archive/ subfolder.
        """
        now = datetime.now(timezone.utc)
        timestamp = now.strftime("%Y%m%d_%H%M%S")
        date_str = now.strftime("%Y-%m-%d %H:%M:%S UTC")

        files_list = files_modified or []
        files_md = "\n".join(f"• `{f}`" for f in files_list) if files_list else "• *(Code files updated during execution)*"

        walkthrough_content = (
            f"# ✅ Completed Tasks & Walkthrough: {title}\n"
            f"*Executed: {date_str}*\n"
            f"*Status: Verified & Completed*\n\n---\n\n"
            f"## 🎯 Objective Summary\n"
            f"Execution completed for implementation plan: **{title}**.\n\n"
            f"## 📂 Files Modified / Created\n"
            f"{files_md}\n\n"
            f"## 🤖 Execution & Verification Report\n"
            f"{execution_response.strip()}\n\n"
            f"---\n"
            f"*Generated by Antigravity Mobile Mission Control*\n"
        )

        # 1. Save top-level active walkthrough
        self.active_walkthrough_file.write_text(walkthrough_content, encoding="utf-8")

        # 2. Save historical copy in archive/ subfolder
        hist_file = self.archive_dir / f"walkthrough_{timestamp}.md"
        hist_file.write_text(walkthrough_content, encoding="utf-8")

        logger.info("Saved active walkthrough to %s (archived to %s)", self.active_walkthrough_file, hist_file)
        return self.active_walkthrough_file

    def get_active_walkthrough(self) -> Optional[str]:
        """Read current completed walkthrough artifact if it exists."""
        if self.active_walkthrough_file.exists():
            try:
                return self.active_walkthrough_file.read_text(encoding="utf-8")
            except Exception as e:
                logger.error("Error reading walkthrough: %s", e)
        return None

    def list_plans(self) -> list[dict]:
        """List all saved plans in project directory (root + archive)."""
        if not self.plans_dir.exists():
            return []

        all_md_files = list(self.plans_dir.glob("*.md")) + list(self.archive_dir.glob("*.md"))
        plans = []
        for f in sorted(all_md_files, key=lambda x: x.stat().st_mtime, reverse=True):
            plans.append({
                "name": f.name,
                "path": str(f),
                "is_archive": "archive" in f.parts,
                "modified": datetime.fromtimestamp(f.stat().st_mtime, timezone.utc).strftime("%Y-%m-%d %H:%M"),
                "size_bytes": f.stat().st_size,
            })
        return plans
